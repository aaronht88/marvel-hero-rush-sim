#!/usr/bin/env python3
"""
Build script: MHR cards.js → js/cards-data.js

This is the MHR-native adapter (no archetype needed; we preserve every
MHR field). Output exposes `window.MHR_CARDS` for the new summon
archive page (archive.html).

Replaces the deleted scripts/build_moz_data.py. Now that the data target
is MHR itself, the chapter label and 'collected' synthetic flag are
dropped — chapter derives from set, and the archive shows all cards
by default. A small set-of-rarities-to-emphasise flag is computed for
the archive's 'highlight' UI.

Schema per card (MHR-native fields, unchanged):
  id            mongo hex (e.g. 6a86a6bc9da74fc0904ed862)
  card_no       BP01-001 (string)
  name          e.g. "「Antimatter」Iron Man"
  type          always 'character' for MHR cardlist
  level         Lv 1-6 (number; SPELL/LOCATION may have empty → coerce 0)
  power         printed power (number; empty → 0)
  attackRange   printed attack range 0-5 (number; empty → 1)
  attribute     Red | Yellow | Blue | Green
  feature       trait line e.g. 'Human/Avengers'
  effect        full effect text
  set           BP01 / SD01-04 / SP01 / EB01 / PB01-A/B / TB01
  rarity        R | SR | GR | MR | UR | SEC | ER | PR | HR | TR
  art           local webp path 'img/cards/<id>.webp'

Plus derived display helpers:
  chapter       MHR chapter label (BP01 → 'MARVEL ORIGIN', etc.)
  highlight     bool — high-rarity cards get the gold ring in the archive

Stdlib only. Run from anywhere.
"""

import json
import sys
from pathlib import Path

REPO = Path("/opt/data/mhr-battle-sim")
SRC = REPO / "js" / "cards.js"
OUT = REPO / "js" / "cards-data.js"

CHAPTERS = {
    "BP01": "MARVEL ORIGIN",
    "SD01": "REALITY STARTER",
    "SD02": "MIND STARTER",
    "SD03": "SPACE STARTER",
    "SD04": "TIME STARTER",
    "SP01": "SPECIAL CARDS",
    "EB01": "EXTRA BOOSTER",
    "PB01": "PROMO BOUNDARY",
    "TB01": "TRADING CARD",
}

# Highlight: high-rarity prints get a gold ring in the archive grid.
HIGHLIGHT_RARITIES = {"SEC", "MR", "UR", "ER", "PR", "HR", "TR"}


def _safe_int(value, default):
    if value is None:
        return default
    try:
        return int(str(value).strip())
    except (ValueError, TypeError):
        return default


def extract_cards_array(src_text: str) -> str:
    """Bracket-counting extractor for 'const CARDS = [...]' literal.

    Tracks in_string state and '\\' escapes so that quote marks inside
    card name / effect text don't confuse the bracket counter. Mirrors
    the logic from the deleted build_moz_data.py.
    """
    idx = src_text.find("const CARDS = [")
    if idx < 0:
        raise SystemExit("ERROR: 'const CARDS = [' not found in cards.js")
    start = idx + len("const CARDS = ")
    depth = 0
    in_str = False
    str_char = ""
    esc = False
    i = start
    while i < len(src_text):
        c = src_text[i]
        if esc:
            esc = False
            i += 1
            continue
        if c == "\\":
            esc = True
            i += 1
            continue
        if in_str:
            if c == str_char:
                in_str = False
        else:
            if c in ("'", '"'):
                in_str = True
                str_char = c
            elif c == "[":
                depth += 1
            elif c == "]":
                depth -= 1
                if depth == 0:
                    return src_text[start : i + 1]
        i += 1
    raise SystemExit("ERROR: unterminated CARDS array")


def adapt(card: dict) -> dict:
    set_code = card.get("set", "BP01")
    rarity = card.get("rarity", "R")
    return {
        "id": card["id"],
        "card_no": card.get("card_no", card["id"][:7]),
        "name": card.get("name", "Unknown"),
        "type": card.get("type", "character"),
        "level": _safe_int(card.get("level"), 0),
        "power": _safe_int(card.get("power"), 0),
        "attackRange": _safe_int(card.get("attackRange"), 1),
        "attribute": card.get("attribute", "Red"),
        "feature": (card.get("feature", "") or "").strip(),
        "effect": card.get("effect", "") or "",
        "set": set_code,
        "rarity": rarity,
        "art": card.get("art", f"img/cards/{card['id']}.webp"),
        "chapter": CHAPTERS.get(set_code, "MARVEL ORIGIN"),
        "highlight": rarity in HIGHLIGHT_RARITIES,
    }


def main():
    if not SRC.exists():
        sys.exit(f"missing source: {SRC}")
    src_text = SRC.read_text(encoding="utf-8")
    array_literal = extract_cards_array(src_text)
    wrapped = '{"_":' + array_literal + "}"
    raw = json.loads(wrapped)["_"]

    cards = [adapt(c) for c in raw]
    n_total = len(cards)
    n_highlight = sum(1 for c in cards if c["highlight"])

    OUT.parent.mkdir(parents=True, exist_ok=True)
    payload = (
        "// AUTO-GENERATED by scripts/build_data.py. Do not hand-edit.\n"
        "// Source: MHR cards.js. Run the build script to refresh.\n"
        f"// Total: {n_total} cards, Highlighted (SEC/MR/UR/ER/PR/HR/TR): {n_highlight}\n"
        "window.MHR_CARDS = "
        + json.dumps(cards, ensure_ascii=False, indent=2)
        + ";\n"
    )
    OUT.write_text(payload, encoding="utf-8")
    print(
        f"WROTE {OUT.relative_to(REPO)}  "
        f"({n_total} cards, {n_highlight} highlighted)"
    )


if __name__ == "__main__":
    main()